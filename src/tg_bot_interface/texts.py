def warning_lines(warnings: list[QueryWarning]) -> str:
    """Предупреждения сервиса простым языком; пустая строка, если предупреждений нет."""
    lines = []
    for w in warnings:
        site = SOURCE_TITLES.get(w.source, w.source)
        if w.code == "categories_unavailable":
            lines.append(f"{site}: немає категорій {esc(w.detail)}")
        elif w.code == "cities_unavailable":
            lines.append(f"{site}: немає міст {esc(w.detail)}")
        elif w.code == "unsupported_filter":
            lines.append(f"{site} не підтримує частину обраних фільтрів")
        elif w.code == "source_skipped":
            lines.append(f"{site} не опитуватиметься: він не може виконати ці фільтри")
        else:
            lines.append(f"{site}: деякі значення фільтрів не враховано")
    unique = list(dict.fromkeys(lines))
    if not unique:
        return ""
    return "⚠️ <b>Зверніть увагу</b>\n" + "\n".join(f"• {line}" for line in unique)
